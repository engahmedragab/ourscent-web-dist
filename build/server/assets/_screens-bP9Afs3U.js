/**
* Build the complete screen list for a platform.
* `enabledModules` controls whether non-core routes are enabled.
* Core routes are always enabled.
*/
function buildScreens(enabledModules, canonicalBase) {
	return SCREEN_TEMPLATES.map(([route, module, requiresAuth, seoIndexed, ogImageMode, layoutVariant, cacheStrategy]) => {
		return {
			route,
			module,
			enabled: module === "core" || enabledModules.has(module),
			requiresAuth,
			seoIndexed,
			canonicalBase,
			ogImageMode,
			redirectWhenOff: "/",
			layoutVariant,
			cacheStrategy
		};
	});
}
